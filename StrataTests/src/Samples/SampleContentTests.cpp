	const std::filesystem::path& GetSamplesDirectory()
	{
		static const std::filesystem::path s_Directory = FileSystem::FromUTF8(STRATA_SOURCE_DIR) / "Samples";
		return s_Directory;
	}

	std::string ReadNotices()
	{
		const std::optional<std::string> notices = FileSystem::ReadText(FileSystem::FromUTF8(STRATA_SOURCE_DIR) / "ThirdPartyNotices.md");
		REQUIRE(notices);
		return *notices;
	}

	bool HasError(const std::vector<std::string>& errors, const std::string& part)
	{
		return std::any_of(errors.begin(), errors.end(), [&](const std::string& error) { return error.find(part) != std::string::npos; });
	}

	void WriteFile(const std::filesystem::path& path, const std::string& text)
	{
		REQUIRE(FileSystem::WriteText(path, text));
	}

	// A file of `bytes` zero bytes, written as a sparse file where the file system allows (sizes are what the budgets read).
	void WriteSizedFile(const std::filesystem::path& path, uint64_t bytes)
	{
		REQUIRE(FileSystem::WriteText(path, ""));
		std::error_code error;
		std::filesystem::resize_file(path, bytes, error);
		REQUIRE_FALSE(error);
	}

	constexpr const char* c_Notices = "# Third-Party Notices\n\n## Sample assets\n\n| Sample | Pack | Source | Author | License | Attribution |\n"
		"| --- | --- | --- | --- | --- | --- |\n| Crafted | Pack | https://example.com/pack | Someone | CC0-1.0 | |\n";

	// A sample that follows every rule: its files, a sound made for it and a credited CC0 pack.
	std::filesystem::path MakeValidSample(const std::filesystem::path& directory)
	{
		WriteFile(directory / "README.md", "# Crafted\n\n![Its picture](Picture.png) made as [the skill](https://example.com/skill.md#making) says.\n");
		WriteFile(directory / "Crafted.stproj", "{}\n");
		REQUIRE(FileSystem::WriteBytes(directory / "Picture.png", Tests::EncodePNG(480, 270, std::vector<uint8_t>(480 * 270 * 4, 128))));
		WriteSizedFile(directory / "Assets" / "Sounds" / "Beep.wav", 1000);
		WriteSizedFile(directory / "Assets" / "Pack" / "Rock.glb", 2000);
		WriteSizedFile(directory / "Assets" / "Pack" / "Rock.png", 3000);
		WriteFile(directory / "Assets" / "Pack" / "Rock.glb.meta", "{}\n");
		WriteFile(directory / "CREDITS.md", "# Credits\n\n| Files | Source | Author | License | Attribution | Changes |\n| --- | --- | --- | --- | --- | --- |\n"
			"| `Assets/Sounds/Beep.wav` | Generated by the agent that made the sample | Strata | Strata | | none |\n"
			"| `Assets/Pack/` | https://example.com/pack (version 1.0) | Someone | CC0-1.0 | | 2 of 40 files |\n");
		return directory;
	}

