"""Generates the sun shadows' blue-noise tile, Strata/src/Strata/Renderer/BlueNoise.h (standard library only).

A 64x64 tile of ranks made by the void-and-cluster method on a torus, with a Gaussian energy kernel (sigma 1.5): an
initial pattern of 410 points (10%) from a fixed seed is relaxed by moving the point of the tightest cluster into the
largest void until that move would put it back; the points are then ranked by removing them from the tightest clusters
(ranks below 410) and the empty cells by filling the largest voids (ranks 410 to 4095). Each rank becomes the byte
rank * 256 // 4096, so every byte value appears exactly 16 times. The output is deterministic: the same arguments give the
same header byte for byte.

Usage: python Tools/GenerateBlueNoise.py [--output <header>] [--check]
"""

import argparse
import math
import pathlib
import random
import sys

SIZE = 64
CELLS = SIZE * SIZE
SIGMA = 1.5
INITIAL_POINTS = 410
SEED = 7
VALUES_PER_LINE = 16
DEFAULT_OUTPUT = pathlib.Path(__file__).resolve().parent.parent / "Strata" / "src" / "Strata" / "Renderer" / "BlueNoise.h"


def make_kernel():
    """The Gaussian energy of a point at each toroidal offset, as rows of the tile."""
    kernel = []
    for dy in range(SIZE):
        ty = min(dy, SIZE - dy)
        row = []
        for dx in range(SIZE):
            tx = min(dx, SIZE - dx)
            row.append(math.exp(-(tx * tx + ty * ty) / (2.0 * SIGMA * SIGMA)))
        kernel.append(row)
    return kernel


class EnergyField:
    """The summed kernel energy of a set of points at every cell, updated as points come and go."""

    def __init__(self, kernel):
        self.kernel = kernel
        self.rows = [[0.0] * SIZE for _ in range(SIZE)]

    def add(self, cell, sign):
        px, py = cell % SIZE, cell // SIZE
        for y in range(SIZE):
            kernel_row = self.kernel[(y - py) % SIZE]
            # rotated[x] is kernel_row[(x - px) % SIZE].
            rotated = kernel_row[SIZE - px:] + kernel_row[:SIZE - px] if px else kernel_row
            row = self.rows[y]
            if sign > 0:
                self.rows[y] = [a + b for a, b in zip(row, rotated)]
            else:
                self.rows[y] = [a - b for a, b in zip(row, rotated)]

    def extreme(self, pattern, wanted, largest):
        """The first cell (row by row) holding `wanted` whose energy is the largest (or smallest)."""
        best_cell = -1
        best_energy = 0.0
        for y in range(SIZE):
            row = self.rows[y]
            base = y * SIZE
            for x in range(SIZE):
                cell = base + x
                if pattern[cell] != wanted:
                    continue
                energy = row[x]
                if best_cell < 0 or (energy > best_energy if largest else energy < best_energy):
                    best_cell = cell
                    best_energy = energy
        return best_cell


def generate():
    kernel = make_kernel()
    rng = random.Random(SEED)
    pattern = [0] * CELLS
    for cell in rng.sample(range(CELLS), INITIAL_POINTS):
        pattern[cell] = 1
    field = EnergyField(kernel)
    for cell in range(CELLS):
        if pattern[cell]:
            field.add(cell, 1)

    # Relaxation: the tightest cluster's point moves into the largest void until it would land where it was.
    while True:
        cluster = field.extreme(pattern, 1, True)
        pattern[cluster] = 0
        field.add(cluster, -1)
        void = field.extreme(pattern, 0, False)
        pattern[void] = 1
        field.add(void, 1)
        if void == cluster:
            break

    ranks = [0] * CELLS
    # Ranks below the initial count: the prototype's points, removed from the tightest clusters.
    prototype = list(pattern)
    prototype_field = EnergyField(kernel)
    prototype_field.rows = [list(row) for row in field.rows]
    for rank in range(INITIAL_POINTS - 1, -1, -1):
        cluster = prototype_field.extreme(prototype, 1, True)
        prototype[cluster] = 0
        prototype_field.add(cluster, -1)
        ranks[cluster] = rank
    # The others: the largest voids filled in turn.
    for rank in range(INITIAL_POINTS, CELLS):
        void = field.extreme(pattern, 0, False)
        pattern[void] = 1
        field.add(void, 1)
        ranks[void] = rank
    return [rank * 256 // CELLS for rank in ranks]


def render_header(values):
    lines = [
        "#pragma once",
        "",
        "#include <cstdint>",
        "",
        "// Generated by Tools/GenerateBlueNoise.py (void and cluster on a 64x64 torus, Gaussian kernel sigma 1.5, 410 initial",
        "// points from seed 7); do not edit: run the tool again.",
        "",
        "namespace Strata::RenderData",
        "{",
        "",
        "\t// The sun shadows' blue-noise tile (Renderer::GetBlueNoiseTexture, Include/Shadows.glsl): 64x64 bytes, row by row, each",
        "\t// value 0-255 exactly 16 times, neighbors far apart in value.",
        "\tinline constexpr uint32_t c_BlueNoiseSize = 64;",
        "\tinline constexpr uint8_t c_BlueNoise[64 * 64] = {",
    ]
    for start in range(0, CELLS, VALUES_PER_LINE):
        chunk = values[start:start + VALUES_PER_LINE]
        lines.append("\t\t" + ", ".join(str(value) for value in chunk) + ("," if start + VALUES_PER_LINE < CELLS else ""))
    lines += ["\t};", "", "}", ""]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description="Generates Strata's blue-noise tile header.")
    parser.add_argument("--output", type=pathlib.Path, default=DEFAULT_OUTPUT, help="the header to write")
    parser.add_argument("--check", action="store_true", help="fail when the header differs from what the tool generates")
    arguments = parser.parse_args()

    header = render_header(generate())
    if arguments.check:
        existing = arguments.output.read_text(encoding="utf-8") if arguments.output.is_file() else ""
        if existing != header:
            print(f"{arguments.output} differs from what the tool generates", file=sys.stderr)
            return 1
        print(f"{arguments.output} is up to date")
        return 0
    arguments.output.write_text(header, encoding="utf-8", newline="\n")
    print(f"Wrote {arguments.output}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
