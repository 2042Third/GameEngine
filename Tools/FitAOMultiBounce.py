#!/usr/bin/env python3
"""Fits ambient occlusion's multi-bounce to a radiosity reference, and writes the fit for the shaders and the tests.

The outputs are committed (CI never runs this script); run it again only to change the fit:

    python3 Tools/FitAOMultiBounce.py            # prints the fit and its errors
    python3 Tools/FitAOMultiBounce.py --write    # also writes the three files below

Occluded light is not lost: the occluders reflect it, lit like the point they hide and with its albedo. Screen-space
ambient occlusion measures only the visibility x (the cosine-weighted share of the hemisphere that sees the sky), so the
renderer brightens it by the light the cavity's own walls send back, a function y(x, rho) of the visibility and the albedo.

Reference: 2D radiosity in cavities whose walls see each other without obstruction (their interiors are convex), so the
view factors between their strips are exact by the crossed-strings rule: V-grooves of opening angles 20, 30, ... 160
degrees and rectangular trenches of width-to-depth ratios 0.25, 0.5, 1, 2 and 4, each surface split into STRIPS strips.
Under a uniform sky of irradiance E0 = 1 on an open plane, strip i receives F_i,sky = 1 - sum_j F_ij from the sky, which
is exactly GTAO's cosine-weighted visibility x_i of its slice; with walls of albedo rho its radiosity B_i = rho (F_i,sky +
sum_j F_ij B_j) is solved by Gauss-Seidel to 1e-9, and the reference multi-bounce visibility is y_i = F_i,sky + sum_j F_ij
B_j, for rho in 0.05, 0.10, ... 0.90.

The reference is not a function of x and rho alone: strips of different cavities with the same visibility receive
different light from their walls (at x = 0.05 and rho = 0.9 from about 0.27 to 0.63), so no model of x and rho comes within
MAX_ERROR of every sample. The fit and its check therefore use the reference's conditional means: per rho, the samples'
mean y in bins of x BIN_WIDTH wide, the best any function of x and rho can do.

Model (decided here, 2026-10-27): the wave-7 spec's polynomial y = x + rho x (1 - x) (p0 + p1 x + p2 rho + p3 rho x) misses
the conditional means by far more than MAX_ERROR (it must vanish with x, while walls of high albedo light even deep
creases; the script prints its errors), so the model is rational, the uniform enclosure's closed form x / (1 - rho (1 - x))
with a fitted enclosure term:

    y = x / (1 - rho (1 - x) h),  h = p0 + p1 x + p2 rho + p3 rho x

1 at x = 1, x at rho = 0, at least x while h >= 0. Its coefficients are the least squares fit of 1 - x / y = rho (1 - x) h
(linear in them) over the conditional means with x of at least MIN_VISIBILITY, the visibilities screen-space ambient
occlusion produces outside crevices a few pixels wide; the normal equations are solved here. The script prints the
largest and RMS error over those means, the RMS over every sample, and for comparison the closed form's and the
polynomial's errors; it fails when the model's largest error over the means exceeds MAX_ERROR.

--write writes, each marked as generated:
  Strata/shaders/Include/AmbientOcclusionFit.glsl          c_AOMultiBounce and AOMultiBounce(visibility, albedo)
  Strata/src/Strata/Renderer/AmbientOcclusionFit.h         the same for C++ (the tests' expected values)
  StrataTests/src/Renderer/AmbientOcclusionFitReference.h  c_AOMultiBounceReference: REFERENCE_SAMPLES conditional means
"""

import argparse
import math
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
STRIPS = 64
GROOVE_ANGLES = [20, 30, 40, 50, 60, 70, 80, 90, 100, 110, 120, 130, 140, 150, 160]
TRENCH_RATIOS = [0.25, 0.5, 1.0, 2.0, 4.0]
ALBEDOS = [round(0.05 * step, 2) for step in range(1, 19)]
MAX_ERROR = 0.03
MIN_VISIBILITY = 0.25
BIN_WIDTH = 0.02
REFERENCE_SAMPLES = 24
TOLERANCE = 1e-9
GENERATED = "Generated by Tools/FitAOMultiBounce.py; do not edit."


def split(start, end, count):
    """A segment from start to end as `count` strips of equal length."""
    def point(t):
        return (start[0] + (end[0] - start[0]) * t, start[1] + (end[1] - start[1]) * t)
    return [(point(index / count), point((index + 1) / count)) for index in range(count)]


def distance(a, b):
    return math.hypot(a[0] - b[0], a[1] - b[1])


def view_factor(strip, other):
    """The share of what leaves `strip` that reaches `other` (2D, unobstructed): Hottel's crossed strings."""
    a1, a2 = strip
    b1, b2 = other
    crossed = distance(a1, b2) + distance(a2, b1)
    uncrossed = distance(a1, b1) + distance(a2, b2)
    return abs(crossed - uncrossed) / (2.0 * distance(a1, a2))


def cavity_samples(surfaces):
    """(x, rho, y) of every strip of a cavity whose surfaces (lists of strips) see each other but not themselves."""
    strips = [(surface, strip) for surface, strips_of in enumerate(surfaces) for strip in strips_of]
    count = len(strips)
    factors = [[0.0] * count for _ in range(count)]
    for i, (surface_i, strip_i) in enumerate(strips):
        for j, (surface_j, strip_j) in enumerate(strips):
            if surface_i != surface_j:
                factors[i][j] = view_factor(strip_i, strip_j)
    sky = [max(0.0, 1.0 - sum(row)) for row in factors]
    samples = []
    for rho in ALBEDOS:
        radiosity = [0.0] * count
        while True:
            change = 0.0
            for i in range(count):
                value = rho * (sky[i] + sum(factors[i][j] * radiosity[j] for j in range(count)))
                change = max(change, abs(value - radiosity[i]))
                radiosity[i] = value
            if change < TOLERANCE:
                break
        for i in range(count):
            irradiance = sky[i] + sum(factors[i][j] * radiosity[j] for j in range(count))
            samples.append((sky[i], rho, irradiance))
    return samples


def reference_samples():
    samples = []
    for angle in GROOVE_ANGLES:
        half = math.radians(angle) * 0.5
        left = split((0.0, 0.0), (-math.sin(half), math.cos(half)), STRIPS)
        right = split((0.0, 0.0), (math.sin(half), math.cos(half)), STRIPS)
        samples += cavity_samples([left, right])
    for ratio in TRENCH_RATIOS:
        floor = split((0.0, 0.0), (ratio, 0.0), STRIPS)
        left = split((0.0, 1.0), (0.0, 0.0), STRIPS)
        right = split((ratio, 0.0), (ratio, 1.0), STRIPS)
        samples += cavity_samples([floor, left, right])
    return samples


def conditional_means(samples):
    """Per rho, the mean (x, y) of the samples in bins of x BIN_WIDTH wide."""
    bins = {}
    last = int(round(1.0 / BIN_WIDTH)) - 1
    for x, rho, y in samples:
        total = bins.setdefault((min(int(x / BIN_WIDTH), last), rho), [0.0, 0.0, 0])
        total[0] += x
        total[1] += y
        total[2] += 1
    return sorted((x / count, rho, y / count) for (_, rho), (x, y, count) in bins.items())


def solve(matrix, vector):
    """Gaussian elimination with partial pivoting."""
    size = len(vector)
    rows = [list(matrix[row]) + [vector[row]] for row in range(size)]
    for column in range(size):
        pivot = max(range(column, size), key=lambda row: abs(rows[row][column]))
        rows[column], rows[pivot] = rows[pivot], rows[column]
        if abs(rows[column][column]) < 1e-15:
            raise ValueError("the normal equations are singular")
        for row in range(size):
            if row != column:
                factor = rows[row][column] / rows[column][column]
                rows[row] = [a - factor * b for a, b in zip(rows[row], rows[column])]
    return [rows[row][size] / rows[row][row] for row in range(size)]


def least_squares(rows):
    """The coefficients minimizing the squared differences of (terms, target) rows."""
    normal = [[0.0] * 4 for _ in range(4)]
    right = [0.0] * 4
    for terms, target in rows:
        for a in range(4):
            right[a] += terms[a] * target
            for b in range(4):
                normal[a][b] += terms[a] * terms[b]
    return solve(normal, right)


def enclosure_terms(x, rho):
    base = rho * (1.0 - x)
    return [base, base * x, base * rho, base * rho * x]


def polynomial_terms(x, rho):
    base = rho * x * (1.0 - x)
    return [base, base * x, base * rho, base * rho * x]


def fit(samples):
    """The model's coefficients: 1 - x / y = rho (1 - x) h over the samples."""
    return least_squares([(enclosure_terms(x, rho), 1.0 - x / y) for x, rho, y in samples if y > 0.0])


def evaluate(p, x, rho):
    enclosure = sum(c * t for c, t in zip(p, enclosure_terms(x, rho)))
    return x / max(1.0 - enclosure, x) if x > 0.0 else 0.0


def fit_polynomial(samples):
    return least_squares([(polynomial_terms(x, rho), y - x) for x, rho, y in samples])


def evaluate_polynomial(p, x, rho):
    return x + sum(c * t for c, t in zip(p, polynomial_terms(x, rho)))


def errors(samples, model):
    differences = [model(x, rho) - y for x, rho, y in samples]
    return max(abs(d) for d in differences), math.sqrt(sum(d * d for d in differences) / len(differences))


def spread(samples, count):
    """`count` samples spread over the fitted range of x and over rho: the nearest to each point of a grid."""
    picked = []
    for index in range(count):
        target_x = MIN_VISIBILITY + (1.0 - MIN_VISIBILITY) * (index % 6 + 0.5) / 6.0
        target_rho = ALBEDOS[(index // 6) * (len(ALBEDOS) - 1) // 3]
        picked.append(min((s for s in samples if s[1] == target_rho), key=lambda s: abs(s[0] - target_x)))
    return picked


def write_outputs(p, picked):
    glsl = f"""#ifndef STRATA_AMBIENT_OCCLUSION_FIT_GLSL
#define STRATA_AMBIENT_OCCLUSION_FIT_GLSL

// {GENERATED}
// Ambient occlusion's multi-bounce: the visibility a surface of `albedo` keeps once the occluders, lit like it and of its
// albedo, reflect light into it (fitted to 2D radiosity in grooves and trenches): visibility / (1 - albedo (1 - visibility)
// h), h = x + y visibility + albedo (z + w visibility). 1 at visibility 1, the visibility itself at albedo 0, per channel;
// never above 1 nor below the visibility.
const vec4 c_AOMultiBounce = vec4({", ".join(f"{c:.9f}" for c in p)});

vec3 AOMultiBounce(float visibility, vec3 albedo)
{{
	vec3 enclosure = albedo * (1.0 - visibility) * (c_AOMultiBounce.x + c_AOMultiBounce.y * visibility + albedo * (c_AOMultiBounce.z + c_AOMultiBounce.w * visibility));
	return visibility / max(1.0 - enclosure, vec3(max(visibility, 1e-4)));
}}

#endif
"""
    header = f"""#pragma once

// {GENERATED}
// Ambient occlusion's multi-bounce (Include/AmbientOcclusionFit.glsl): the visibility a surface of `albedo` keeps once the
// occluders, lit like it and of its albedo, reflect light into it. 1 at visibility 1, the visibility itself at albedo 0.

#include <glm/glm.hpp>

namespace Strata
{{

	constexpr glm::vec4 c_AOMultiBounce = {{ {", ".join(f"{c:.9f}f" for c in p)} }};

	inline glm::vec3 AOMultiBounce(float visibility, const glm::vec3& albedo)
	{{
		const glm::vec3 enclosure = albedo * (1.0f - visibility)
			* (c_AOMultiBounce.x + c_AOMultiBounce.y * visibility + albedo * (c_AOMultiBounce.z + c_AOMultiBounce.w * visibility));
		return visibility / glm::max(1.0f - enclosure, glm::vec3(glm::max(visibility, 1e-4f)));
	}}

}}
"""
    rows = ",\n".join(f"\t\t{{ {x:.6f}f, {rho:.2f}f, {y:.6f}f }}" for x, rho, y in picked)
    reference = f"""#pragma once

// {GENERATED}
// Conditional means of the multi-bounce fit's radiosity reference within its fitted range: (visibility, albedo, the mean
// visibility the radiosity gives there).

#include <array>

namespace Strata::Tests
{{

	struct AOMultiBounceSample
	{{
		float Visibility;
		float Albedo;
		float Reference;
	}};

	constexpr std::array<AOMultiBounceSample, {len(picked)}> c_AOMultiBounceReference = {{ {{
{rows}
	}} }};

}}
"""
    outputs = {
        ROOT / "Strata" / "shaders" / "Include" / "AmbientOcclusionFit.glsl": glsl,
        ROOT / "Strata" / "src" / "Strata" / "Renderer" / "AmbientOcclusionFit.h": header,
        ROOT / "StrataTests" / "src" / "Renderer" / "AmbientOcclusionFitReference.h": reference,
    }
    for path, text in outputs.items():
        with open(path, "w", encoding="utf-8", newline="\n") as file:
            file.write(text)
        print(f"wrote {path.relative_to(ROOT)}")


def main():
    parser = argparse.ArgumentParser(description="Fits ambient occlusion's multi-bounce to a radiosity reference.")
    parser.add_argument("--write", action="store_true", help="write the GLSL, C++ and test reference files")
    args = parser.parse_args()

    samples = reference_samples()
    means = [m for m in conditional_means(samples) if m[0] >= MIN_VISIBILITY]
    p = fit(means)
    largest, rms = errors(means, lambda x, rho: evaluate(p, x, rho))
    _, sample_rms = errors(samples, lambda x, rho: evaluate(p, x, rho))
    closed_largest, closed_rms = errors(means, lambda x, rho: x / (1.0 - rho * (1.0 - x)))
    q = fit_polynomial(means)
    polynomial_largest, polynomial_rms = errors(means, lambda x, rho: evaluate_polynomial(q, x, rho))
    print(f"{len(samples)} samples, {len(means)} conditional means with x >= {MIN_VISIBILITY}")
    print(f"coefficients {', '.join(f'{c:.6f}' for c in p)}")
    print(f"model: largest error {largest:.4f}, RMS {rms:.4f} over the means; RMS {sample_rms:.4f} over every sample")
    print(f"uniform enclosure x / (1 - rho (1 - x)): largest error {closed_largest:.4f}, RMS {closed_rms:.4f}")
    print(f"the spec's polynomial: largest error {polynomial_largest:.4f}, RMS {polynomial_rms:.4f}")
    if largest > MAX_ERROR:
        print(f"error: the model's largest error exceeds {MAX_ERROR}: it needs another term", file=sys.stderr)
        return 1
    if args.write:
        write_outputs(p, spread(means, REFERENCE_SAMPLES))
    return 0


if __name__ == "__main__":
    sys.exit(main())
